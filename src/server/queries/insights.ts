// ---------------------------------------------------------------- statistics helpers (pure)

/**
 * Below this many completed observations the 90th percentile is not reported.
 * 10 is the threshold set for this demonstration; the pilot proposal (§6.1)
 * proposes 30 for real measurement, for the lab to agree.
 */
export const MIN_N_FOR_P90 = 10;
export const P90_TOO_SMALL = "Sample too small for p90";
export const P90_THRESHOLD_NOTE =
  "This demo withholds the 90th percentile below n = 10. The pilot proposal suggests 30 completed observations for real measurement, for the lab to agree.";

/**
 * Nearest-rank percentile: the value at rank ⌈p/100 × n⌉ of the sorted
 * values (1-based). Every reported value is an actually observed value.
 * Returns null for an empty sample.
 */
export function nearestRank(sortedAsc: readonly number[], p: number): number | null {
  const n = sortedAsc.length;
  if (!n) return null;
  if (p <= 0) return sortedAsc[0];
  if (p >= 100) return sortedAsc[n - 1];
  const rank = Math.ceil((p * n) / 100 - 1e-9);
  return sortedAsc[Math.min(n, Math.max(1, rank)) - 1];
}

/** Median by the same nearest-rank method (50th percentile). */
export function median(values: readonly number[]): number | null {
  return nearestRank([...values].sort((a, b) => a - b), 50);
}

/** 90th percentile, or null with a reason when n < MIN_N_FOR_P90. */
export function p90(values: readonly number[]): { value: number | null; reason: string | null } {
  if (values.length === 0) return { value: null, reason: "No completed observations" };
  if (values.length < MIN_N_FOR_P90) return { value: null, reason: P90_TOO_SMALL };
  return { value: nearestRank([...values].sort((a, b) => a - b), 90), reason: null };
}

export interface TimingItem {
  ref: string;
  /** Start event time (UTC ISO) or null when the event was not recorded. */
  start: string | null;
  /** End event time (UTC ISO) or null when not recorded. */
  end: string | null;
  /** True when the item has not reached its end event (still open at the snapshot). */
  open: boolean;
}

export interface DurationSummary {
  /** Items considered (completed + still open + missing). */
  total: number;
  /** Completed items with valid start and end (the timing sample). */
  n: number;
  medianMin: number | null;
  p90Min: number | null;
  /** Why p90 is not shown, e.g. "Sample too small for p90". */
  p90Note: string | null;
  minMin: number | null;
  maxMin: number | null;
  /** Sorted completed durations in minutes (for histograms and tables). */
  values: number[];
  stillOpen: number;
  /** Age of the oldest still-open item at the snapshot (minutes); null if none or all ages unknown. */
  stillOpenOldestMin: number | null;
  /** Still-open items whose start time is unknown (age unknown, never 0). */
  stillOpenAgeUnknown: number;
  /** Closed items with a missing or invalid start/end event: excluded from timing and counted here. */
  missing: number;
  /** missing as a percent of total (one decimal); null when total is 0. */
  missingPct: number | null;
  missingRefs: string[];
  /** Where the sample came from, shown beside it (today: "Seeded synthetic + this session", and what the end events were). */
  provenance?: string;
}

/**
 * Split items into completed / still open / missing and summarize completed
 * durations. Still-open and missing items never enter the median or p90.
 */
export function summarizeTimings(items: readonly TimingItem[], asOf: string): DurationSummary {
  const values: number[] = [];
  let stillOpen = 0;
  let stillOpenAgeUnknown = 0;
  let oldest: number | null = null;
  const missingRefs: string[] = [];
  const asOfMs = Date.parse(asOf);
  for (const it of items) {
    if (it.open) {
      stillOpen += 1;
      if (!it.start) stillOpenAgeUnknown += 1;
      else {
        const age = Math.max(0, Math.round((asOfMs - Date.parse(it.start)) / 60_000));
        oldest = oldest === null ? age : Math.max(oldest, age);
      }
      continue;
    }
    if (!it.start || !it.end) {
      missingRefs.push(it.ref);
      continue;
    }
    const d = (Date.parse(it.end) - Date.parse(it.start)) / 60_000;
    if (!Number.isFinite(d) || d < 0) {
      missingRefs.push(it.ref); // end before start: invalid event data, reported as missing
      continue;
    }
    values.push(Math.round(d));
  }
  values.sort((a, b) => a - b);
  const p = p90(values);
  return {
    total: items.length,
    n: values.length,
    medianMin: nearestRank(values, 50),
    p90Min: p.value,
    p90Note: p.reason,
    minMin: values.length ? values[0] : null,
    maxMin: values.length ? values[values.length - 1] : null,
    values,
    stillOpen,
    stillOpenOldestMin: oldest,
    stillOpenAgeUnknown,
    missing: missingRefs.length,
    missingPct: items.length ? Math.round((missingRefs.length / items.length) * 1000) / 10 : null,
    missingRefs,
  };
}

/** "45 min", "2 h 05 min", "3 d 4 h". Null → "Unknown". */
export function fmtMinutes(min: number | null | undefined): string {
  if (min === null || min === undefined || !Number.isFinite(min)) return "Unknown";
  const m = Math.round(min);
  if (m < 60) return `${m} min`;
  const h = Math.floor(m / 60);
  if (h < 48) return `${h} h ${String(m % 60).padStart(2, "0")} min`;
  const d = Math.floor(h / 24);
  return `${d} d ${h % 24} h`;
}

