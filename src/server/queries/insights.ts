const HOUR_FMT = new Intl.DateTimeFormat("en-US", { timeZone: "America/New_York", hourCycle: "h23", hour: "2-digit" });

/** Local (ET) clock hour 0–23 of an ISO instant. */
export function localHour(iso: string): number {
  return Number(HOUR_FMT.format(new Date(iso))) % 24;
}

function hourLabel(h: number): string {
  return `${String(h).padStart(2, "0")}:00`;
}

const DELAY_BUCKETS: { label: string; min: number; max: number | null }[] = [
  { label: "Under 1 h", min: 0, max: 60 },
  { label: "1 to 2 h", min: 60, max: 120 },
  { label: "2 to 4 h", min: 120, max: 240 },
  { label: "4 to 8 h", min: 240, max: 480 },
  { label: "8 to 12 h", min: 480, max: 720 },
  { label: "12 h or more", min: 720, max: null },
];

export function histogram(values: readonly number[]): Histogram[] {
  return DELAY_BUCKETS.map((b) => ({
    label: b.label,
    minMin: b.min,
    maxMin: b.max,
    count: values.filter((v) => v >= b.min && (b.max === null || v < b.max)).length,
  }));
}

function ageBucket(min: number): 0 | 1 | 2 | 3 {
  if (min < 60) return 0;
  if (min < 240) return 1;
  if (min < 480) return 2;
  return 3;
}

/** Compute every insight metric. Read-only. */
export function getInsights(db: DB, f: InsightsFilters = {}): InsightsData {
  const asOf = readClock(db).now;
  const demoDay = getSetting(db, "demo_day") ?? labDay(asOf);

  // ---- options
  const days = (db.prepare("SELECT DISTINCT day FROM ops_event ORDER BY day").all() as { day: string }[]).map((r) => r.day);
  const offices = db.prepare("SELECT id, name AS label FROM office ORDER BY name").all() as Option[];
  const doctors = db
    .prepare("SELECT id, display_name AS label, color_token AS color FROM staff WHERE role = 'pathologist' ORDER BY display_name")
    .all() as DoctorOption[];
  const from = f.from && days.includes(f.from) ? f.from : days[0] ?? demoDay;
  const toRaw = f.to && days.includes(f.to) ? f.to : days[days.length - 1] ?? demoDay;
  const to = toRaw < from ? from : toRaw;
  const office = f.office && offices.some((o) => o.id === f.office) ? f.office : null;
  const doctor = f.doctor && doctors.some((d) => d.id === f.doctor) ? f.doctor : null;
  const priorDays = days.filter((d) => d >= from && d <= to);
  const nDays = Math.max(1, priorDays.length);

  // ---- illustrative prior-day events grouped per case reference
  const rows = db
    .prepare(
      `SELECT day, case_ref, pathologist_id, office_id, event, at FROM ops_event
        WHERE illustrative = 1 AND day >= @from AND day <= @to
          AND (@office IS NULL OR office_id = @office) AND (@doctor IS NULL OR pathologist_id = @doctor)
        ORDER BY day, case_ref, at`,
    )
    .all({ from, to, office, doctor }) as OpsRow[];
  const cases = new Map<string, CaseEvents>();
  for (const r of rows) {
    let c = cases.get(r.case_ref);
    if (!c) {
      c = { ref: r.case_ref, day: r.day, office: r.office_id, pathologist: r.pathologist_id, ev: new Map() };
      cases.set(r.case_ref, c);
    }
    if (!c.ev.has(r.event)) c.ev.set(r.event, r.at);
  }
  const all = [...cases.values()];

  // ---- arrivals by hour
  const priorByHour = new Map<number, number>();
  let priorArrivals = 0;
  let priorUnknownTime = 0;
  for (const c of all) {
    const at = c.ev.get("received");
    if (!at) {
      priorUnknownTime += 1; // a case in the window with no recorded arrival time: counted, not plotted
      continue;
    }
    priorArrivals += 1;
    const h = localHour(at);
    priorByHour.set(h, (priorByHour.get(h) ?? 0) + 1);
  }
  const todayItems = (db.prepare("SELECT received_at FROM intake_item").all() as { received_at: string | null }[]).filter(
    (r) => !r.received_at || labDay(r.received_at) === demoDay,
  );
  const todayByHour = new Map<number, number>();
  let todayUnknownTime = 0;
  for (const r of todayItems) {
    if (!r.received_at) {
      todayUnknownTime += 1;
      continue;
    }
    const h = localHour(r.received_at);
    todayByHour.set(h, (todayByHour.get(h) ?? 0) + 1);
  }
  const hours = [...priorByHour.keys(), ...todayByHour.keys()];
  const minH = Math.min(6, ...hours);
  const maxH = Math.max(18, ...hours);
  const bins: HourBin[] = [];
  for (let h = minH; h <= maxH; h++) {
    const total = priorByHour.get(h) ?? 0;
    bins.push({ hour: h, label: hourLabel(h), priorTotal: total, priorMean: Math.round((total / nDays) * 10) / 10, today: todayByHour.get(h) ?? 0 });
  }

  // ---- clarifications (illustrative)
  const clarCases = all.filter((c) => c.ev.has("clarification_sent") || c.ev.has("clarification_answered") || c.ev.has("clarification_resolved"));
  const priorAck = summarizeTimings(
    clarCases.map((c) => {
      const answered = c.ev.get("clarification_answered") ?? null;
      const resolved = c.ev.get("clarification_resolved") ?? null;
      return { ref: c.ref, start: c.ev.get("clarification_sent") ?? null, end: answered, open: !answered && !resolved };
    }),
    asOf,
  );
  const priorResolve = summarizeTimings(
    clarCases.map((c) => {
      const resolved = c.ev.get("clarification_resolved") ?? null;
      return { ref: c.ref, start: c.ev.get("clarification_sent") ?? null, end: resolved, open: !resolved };
    }),
    asOf,
  );

  // ---- clarifications (today, live synthetic)
  const liveClar = (
    db
      .prepare(`SELECT display_id, state, created_at, sent_at, acknowledged_at, answered_at, resolved_at, answer_channel FROM clarification`)
      .all() as {
      display_id: string; state: string; created_at: string; sent_at: string | null; acknowledged_at: string | null; answered_at: string | null; resolved_at: string | null;
      answer_channel: string | null;
    }[]
  ).filter((c) => labDay(c.created_at) === demoDay);
  /** How an office answer arrived: simulated (portal or EMA message) or recorded by staff (phone, other). */
  const answerSource = (c: (typeof liveClar)[number]) =>
    !c.answered_at ? null : c.answer_channel?.startsWith("simulated_") ? "simulated" : c.answer_channel?.endsWith("_recorded_by_staff") ? "staff" : "unknown";
  const answerSourcesText = (items: (typeof liveClar)[number][], ackCounts: boolean) => {
    const n = { simulated: 0, staff: 0, unknown: 0, ackOnly: 0 };
    for (const c of items) {
      const src = answerSource(c);
      // M2 ends at the first acknowledgement or reply: an acknowledgement before any answer is its own kind.
      if (ackCounts && c.acknowledged_at && (!c.answered_at || c.acknowledged_at < c.answered_at)) n.ackOnly += 1;
      else if (src) n[src] += 1;
    }
    const bits = [
      `${n.simulated} simulated office ${n.simulated === 1 ? "answer" : "answers"}`,
      `${n.staff} recorded by staff`,
      ...(n.unknown ? [`${n.unknown} with the channel not recorded`] : []),
      ...(ackCounts && n.ackOnly ? [`${n.ackOnly} ended by an acknowledgement`] : []),
    ];
    return `${TODAY_PROVENANCE}. End events: ${bits.join(", ")}.`;
  };
  const earliest = (...xs: (string | null)[]) => xs.filter((x): x is string => !!x).sort()[0] ?? null;
  const ackStates = new Set(["acknowledged", "answered", "reviewed", "resolved"]);
  // Excluded: drafts never sent, and questions canceled before sending (pilot M2 exclusions).
  const todayNotSent = liveClar.filter((c) => c.state === "drafted" && !c.sent_at).length;
  const todayCanceledBeforeSend = liveClar.filter((c) => c.state === "canceled" && !c.sent_at).length;
  const sentToday = liveClar.filter((c) => !!c.sent_at || (c.state !== "drafted" && c.state !== "canceled"));
  const ackEnd = (c: (typeof liveClar)[number]) => earliest(c.acknowledged_at, c.answered_at);
  // Canceled after sending: kept for M2 when it was acknowledged first; otherwise it has no end event and is counted apart.
  const canceledAfterSend = sentToday.filter((c) => c.state === "canceled");
  const todayCanceledUnacknowledged = canceledAfterSend.filter((c) => !ackEnd(c)).length;
  const ackSample = sentToday.filter((c) => c.state !== "canceled" || !!ackEnd(c));
  const todayAck = summarizeTimings(
    ackSample.map((c) => {
      const end = ackEnd(c);
      return { ref: c.display_id, start: c.sent_at, end, open: !end && !ackStates.has(c.state) && c.state !== "canceled" };
    }),
    asOf,
  );
  todayAck.provenance = answerSourcesText(ackSample.filter((c) => !!ackEnd(c)), true);
  // M3: a canceled clarification never reaches a reviewed resolution, so it is excluded (and counted).
  const resolveSample = sentToday.filter((c) => c.state !== "canceled");
  const todayResolve = summarizeTimings(
    resolveSample.map((c) => ({ ref: c.display_id, start: c.sent_at, end: c.resolved_at, open: c.state !== "resolved" })),
    asOf,
  );
  todayResolve.provenance = answerSourcesText(resolveSample.filter((c) => c.state === "resolved"), false);

  // ---- gross approval -> source entry (illustrative)
  const grossCases = all.filter((c) => c.ev.has("gross_approved") || c.ev.has("source_entered"));
  const priorGross = summarizeTimings(
    grossCases.map((c) => {
      const entered = c.ev.get("source_entered") ?? null;
      return { ref: c.ref, start: c.ev.get("gross_approved") ?? null, end: entered, open: !entered };
    }),
    asOf,
  );
  const entryHourCounts = new Map<number, number>();
  let priorEntries = 0;
  let eveningEntries = 0;
  for (const c of grossCases) {
    const e = c.ev.get("source_entered");
    if (!e) continue;
    priorEntries += 1;
    const h = localHour(e);
    entryHourCounts.set(h, (entryHourCounts.get(h) ?? 0) + 1);
    if (h >= 18) eveningEntries += 1;
  }
  const entryHours = [...entryHourCounts.entries()].sort((a, b) => a[0] - b[0]).map(([hour, count]) => ({ hour, label: hourLabel(hour), count }));

  // ---- gross approval -> source entry (today, live synthetic)
  const liveGross = (
    db
      .prepare(
        `SELECT gr.id, gr.state, gr.source_update_state, gr.approved_at, gr.source_entry_at, a.accession_number, sp.designation
           FROM gross_record gr JOIN specimen_part sp ON sp.id = gr.specimen_part_id JOIN accession a ON a.id = sp.accession_id
          WHERE gr.state = 'approved_for_downstream' AND sp.status <> 'canceled'`,
      )
      .all() as {
      id: string; state: string; source_update_state: string; approved_at: string | null; source_entry_at: string | null; accession_number: string; designation: string;
    }[]
  ).filter((g) => (g.approved_at ? labDay(g.approved_at) === demoDay : true));
  const todayGross = summarizeTimings(
    liveGross.map((g) => {
      const entered = g.source_update_state === "entered_attested" || g.source_update_state === "source_acknowledged";
      return { ref: `${g.accession_number} ${g.designation}`, start: g.approved_at, end: entered ? g.source_entry_at : null, open: !entered };
    }),
    asOf,
  );
  todayGross.provenance = `${TODAY_PROVENANCE}. "Entered" is a staff attestation, not a source acknowledgement.`;

  // ---- unresolved work age (live snapshot)
  const workAge = workAgeSnapshot(db, asOf);

  // ---- cases by assigned dermatopathologist
  const doctorName = new Map(doctors.map((d) => [d.id, d] as const));
  const priorByDoctor = new Map<string | null, number>();
  for (const c of all) {
    // Every case in the window counts, whether or not its arrival time was recorded.
    priorByDoctor.set(c.pathologist, (priorByDoctor.get(c.pathologist) ?? 0) + 1);
  }
  const todayAcc = db
    .prepare("SELECT assigned_pathologist_id AS p, COUNT(*) AS n FROM accession WHERE received_day = ? AND is_prior_day = 0 GROUP BY assigned_pathologist_id")
    .all(demoDay) as { p: string | null; n: number }[];
  const todayByDoctor = new Map(todayAcc.map((r) => [r.p, r.n] as const));
  const todayRoutingExceptions = (
    db
      .prepare(
        `SELECT COUNT(*) AS n FROM routing_decision rd JOIN intake_item ii ON ii.id = rd.intake_item_id
          WHERE ${OPEN_ROUTING_EXCEPTION_SQL}`,
      )
      .get() as { n: number }
  ).n;
  const doctorIds: (string | null)[] = doctors.map((d) => d.id);
  if (priorByDoctor.has(null) || todayByDoctor.has(null)) doctorIds.push(null);
  const doctorRow = (id: string | null): DoctorCount => {
    const d = id ? doctorName.get(id) : null;
    const total = priorByDoctor.get(id) ?? 0;
    return {
      id,
      name: d ? d.label : "Unassigned",
      color: d?.color ?? null,
      priorTotal: total,
      priorMean: Math.round((total / nDays) * 10) / 10,
      today: todayByDoctor.get(id) ?? 0,
    };
  };
  // The doctor filter narrows the illustrative rows only; today's rows always cover every dermatopathologist.
  const byDoctorRows: DoctorCount[] = doctorIds.filter((id) => !doctor || id === doctor).map(doctorRow);
  const todayDoctorRows: DoctorCount[] = doctorIds.map(doctorRow);

  return {
    asOf,
    demoDay,
    todayProvenance: TODAY_PROVENANCE,
    filters: { from, to, office, doctor },
    options: { days, offices, doctors },
    priorDays,
    arrivals: { bins, priorArrivals, priorUnknownTime, todayArrivals: todayItems.length - todayUnknownTime, todayUnknownTime },
    clarAck: { prior: priorAck, today: todayAck, todayNotSent, todayCanceledBeforeSend, todayCanceledUnacknowledged },
    clarResolve: { prior: priorResolve, today: todayResolve, todayCanceledAfterSend: canceledAfterSend.length },
    grossEntry: { prior: priorGross, today: todayGross, histogram: histogram(priorGross.values), entryHours, eveningEntries, priorEntries },
    workAge,
    byDoctor: {
      rows: byDoctorRows,
      todayRows: todayDoctorRows,
      priorTotal: [...priorByDoctor.values()].reduce((a, b) => a + b, 0),
      todayTotal: todayAcc.reduce((a, r) => a + r.n, 0),
      todayRoutingExceptions,
    },
  };
}

/** Demo roles allowed to close an item, from the permission that closes it ("Accessioning lead, Operations supervisor"). */
function closers(permission: Permission): string {
  return rolesFor(permission).map((r) => ROLE_LABEL[r]).join(", ");
}

/**
 * M5 snapshot of open work by type with age buckets (under 1 h, 1–4 h, 4–8 h,
 * over 8 h) and the owning role. A type whose records cannot be read is
 * reported as unreadable (count null), never as "none open".
 */
export function workAgeSnapshot(db: DB, asOf: string): { rows: WorkAgeRow[]; total: number; unreadableTypes: number } {
  const types: { type: string; label: string; link: string; owner: Permission; sql: string }[] = [
    {
      type: "clarification",
      label: "Open clarifications",
      link: "/clarifications",
      owner: "clarification.resolve",
      sql: `SELECT display_id AS ref, created_at AS created FROM clarification WHERE state IN (${OPEN_CLARIFICATION_STATES.map((s) => `'${s}'`).join(",")})`,
    },
    { type: "hold", label: "Active holds", link: "/operations", owner: "hold.release", sql: "SELECT display_id AS ref, placed_at AS created FROM hold WHERE status = 'active'" },
    {
      type: "source_entry",
      label: "Approved gross records awaiting source entry",
      link: "/worklist",
      owner: "gross.recordSourceEntry",
      // The shared source-entry backlog (lib/domain): canceled parts excluded.
      sql: `SELECT a.accession_number || ' ' || sp.designation AS ref, gr.approved_at AS created FROM gross_record gr
              JOIN specimen_part sp ON sp.id = gr.specimen_part_id JOIN accession a ON a.id = sp.accession_id
             WHERE ${AWAITING_SOURCE_ENTRY_SQL}`,
    },
    {
      type: "print_unknown",
      label: "Print jobs with unknown outcome",
      link: "/materials?tab=print",
      owner: "print.reconcile",
      sql: "SELECT display_id AS ref, COALESCE(submitted_at, created_at) AS created FROM print_job WHERE state = 'unknown_outcome'",
    },
    {
      type: "tray",
      label: "Trays not verified",
      link: "/materials?tab=trays",
      owner: "tray.assemble",
      sql: "SELECT display_id AS ref, opened_at AS created FROM tray WHERE status IN ('open','assembling','exception')",
    },
    {
      type: "retrieval",
      label: "Open retrieval requests",
      link: "/materials?tab=retrieval",
      owner: "retrieval.pick",
      sql: "SELECT display_id AS ref, created_at AS created FROM retrieval_request WHERE status IN ('open','picking','partially_retrieved')",
    },
    {
      type: "work_order",
      label: "Open work orders",
      link: "/worklist",
      owner: "workorder.review",
      sql: "SELECT display_id AS ref, requested_at AS created FROM work_order WHERE status IN ('requested','in_progress','cancel_review','amended_review')",
    },
  ];
  const asOfMs = Date.parse(asOf);
  let total = 0;
  let unreadableTypes = 0;
  const rows: WorkAgeRow[] = types.map((t) => {
    let items: { ref: string; created: string | null }[];
    try {
      items = db.prepare(t.sql).all() as { ref: string; created: string | null }[];
    } catch (e) {
      log("error", "insights.work_age_failed", { type: t.type, error: e });
      unreadableTypes += 1;
      return {
        type: t.type,
        label: t.label,
        ownerRoles: closers(t.owner),
        count: null,
        readError: "Unknown: could not be read",
        buckets: [0, 0, 0, 0],
        ageUnknown: 0,
        medianMin: null,
        p90Min: null,
        p90Note: null,
        oldestMin: null,
        oldestRef: null,
        link: t.link,
      };
    }
    const buckets: [number, number, number, number] = [0, 0, 0, 0];
    const ages: number[] = [];
    let ageUnknown = 0;
    let oldest: { min: number; ref: string } | null = null;
    for (const it of items) {
      const createdMs = it.created ? Date.parse(it.created) : NaN;
      if (!Number.isFinite(createdMs)) {
        ageUnknown += 1;
        continue;
      }
      const age = Math.max(0, Math.round((asOfMs - createdMs) / 60_000));
      ages.push(age);
      buckets[ageBucket(age)] += 1;
      if (!oldest || age > oldest.min) oldest = { min: age, ref: it.ref };
    }
    ages.sort((a, b) => a - b);
    const p = p90(ages);
    total += items.length;
    return {
      type: t.type,
      label: t.label,
      ownerRoles: closers(t.owner),
      count: items.length,
      readError: null,
      buckets,
      ageUnknown,
      medianMin: nearestRank(ages, 50),
      p90Min: p.value,
      p90Note: items.length ? p.reason : null,
      oldestMin: oldest?.min ?? null,
      oldestRef: oldest?.ref ?? null,
      link: t.link,
    };
  });
  return { rows, total, unreadableTypes };
}
