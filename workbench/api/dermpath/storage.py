"""Private object storage and signed, short-lived slide access tokens.

``LocalObjectStore`` (default) keeps objects under ``var/objects`` (mode 0700 dirs, 0600
files), never under a web root. Objects are reachable only through API routes.

``S3ObjectStore`` targets S3-compatible storage (MinIO in docker-compose). boto3 is
imported lazily; if it is not installed the store reports ``missing_dependency`` in
``/health`` and every operation raises :class:`StoreDependencyError`. Nothing crashes at
import time. UNVERIFIED here: no MinIO/S3 endpoint is available in this environment.

Object keys are generated by the server (``projects/<pid>/slides/<sid>/original.svs``);
user-supplied filenames are never used as keys.

Writes always go to a uniquely named temporary file (pid + uuid) and are published
atomically, so concurrent writers never collide on a temp name. Write-once helpers
(design §10):

* :meth:`ObjectStore.put_if_absent` publishes an object only if the key is free; when the
  key exists it verifies the stored bytes have the same sha256 (and raises
  :class:`ObjectConflictError` otherwise). It never overwrites. Locally the publish is a
  hard link (atomic, fails if the name exists); on S3 it is a conditional ``PUT`` with
  ``If-None-Match: *``.
* :meth:`ObjectStore.put_file_streaming` streams a file or file object in bounded memory
  and returns its sha256 and size (overwrite semantics, or write-once with
  ``if_absent=True``).
* :meth:`ObjectStore.put_content_addressed` stores bytes or a stream under
  ``<prefix>/<sha256><suffix>`` (write-once) and returns ``(key, sha256)``.
"""

from __future__ import annotations

import errno
import hashlib
import logging
