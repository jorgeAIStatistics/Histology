log = logging.getLogger("dermpath.storage")

_KEY_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.\-/]{0,299}$")
ACCESS_CONTEXT = "slide-access"
_CHUNK = 1024 * 1024

#: What the write helpers accept: bytes, a filesystem path, or a readable binary file object.
Source = bytes | bytearray | memoryview | str | os.PathLike | BinaryIO


class StoreError(Exception):
    pass


class StoreDependencyError(StoreError):
    def __init__(self, dependency: str, message: str) -> None:
        super().__init__(message)
        self.dependency = dependency


class ObjectConflictError(StoreError):
    """A write-once key already holds different bytes. Nothing was overwritten."""

    def __init__(self, key: str, expected_sha256: str, actual_sha256: str) -> None:
        super().__init__(f"object {key} already exists with sha256 {actual_sha256}, not {expected_sha256}; "
                         "write-once objects are never overwritten")
        self.key = key
        self.expected_sha256 = expected_sha256
        self.actual_sha256 = actual_sha256


@dataclass(frozen=True)
class PutResult:
    key: str
    sha256: str
    size: int
    created: bool  # False when an identical object was already stored under the key


def _temp_name(dest: Path) -> Path:
    """A per-writer temp path next to ``dest`` (same filesystem; pid + uuid, so writers never share one)."""
    return dest.with_name(f".{dest.name}.{os.getpid()}.{uuid.uuid4().hex}.tmp")


def _is_bytes(src) -> bool:
    return isinstance(src, (bytes, bytearray, memoryview))


def _is_path(src) -> bool:
    return isinstance(src, (str, os.PathLike))


def _hash_bytes(data) -> tuple[str, int]:
    data = bytes(data)
    return hashlib.sha256(data).hexdigest(), len(data)


def _hash_file(path) -> tuple[str, int]:
    h, n = hashlib.sha256(), 0
    with open(path, "rb") as fh:
        for block in iter(lambda: fh.read(_CHUNK), b""):
            h.update(block)
            n += len(block)
    return h.hexdigest(), n


def _stream_to(src: Source, dest_fh: BinaryIO) -> tuple[str, int]:
    """Copy ``src`` into an open file in bounded memory; return ``(sha256, size)``."""
    h, n = hashlib.sha256(), 0
    if _is_bytes(src):
        data = bytes(src)
        dest_fh.write(data)
        return hashlib.sha256(data).hexdigest(), len(data)
    fh = open(src, "rb") if _is_path(src) else src
    try:
        for block in iter(lambda: fh.read(_CHUNK), b""):
            h.update(block)
            dest_fh.write(block)
            n += len(block)
    finally:
        if fh is not src:
            fh.close()
    return h.hexdigest(), n


def _write_temp(src: Source, tmp: Path) -> tuple[str, int]:
    """Write ``src`` to a new 0600 file at ``tmp`` (fsynced); return ``(sha256, size)``."""
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "wb") as fh:
        sha, size = _stream_to(src, fh)
        fh.flush()
        os.fsync(fh.fileno())
    return sha, size


def _check_expected(key: str, sha: str, expected_sha256: str | None) -> None:
    if expected_sha256 is not None and sha != expected_sha256:
        raise StoreError(f"refusing to store {key}: source sha256 {sha} does not match the expected {expected_sha256}")


def validate_key(key: str) -> str:
    if not _KEY_RE.match(key) or ".." in key.split("/") or "//" in key or key.endswith("/"):
        raise StoreError(f"invalid object key: {key!r}")
    return key


class ObjectStore(ABC):
    backend: str = "abstract"

    @abstractmethod
    def put_file(self, key: str, src: Path, *, move: bool = False) -> int: ...

    @abstractmethod
    def put_bytes(self, key: str, data: bytes) -> int: ...

    @abstractmethod
    def get_bytes(self, key: str) -> bytes: ...

    @abstractmethod
    def open_read(self, key: str) -> BinaryIO: ...

    @abstractmethod
    def exists(self, key: str) -> bool: ...

    @abstractmethod
    def size(self, key: str) -> int: ...

    @abstractmethod
    def delete(self, key: str) -> None: ...

    @abstractmethod
    def local_path(self, key: str) -> Path:
        """A filesystem path for libraries that need one (OpenSlide). S3 downloads to a
        private cache first."""

    @abstractmethod
    def health(self) -> dict: ...

    def sha256(self, key: str) -> str:
        h = hashlib.sha256()
        with self.open_read(key) as fh:
            for block in iter(lambda: fh.read(1024 * 1024), b""):
                h.update(block)
        return h.hexdigest()

    # ------------------------------------------------------------- write-once helpers
    # Generic implementations (head-then-put: NOT atomic between the check and the write).
    # LocalObjectStore and S3ObjectStore override put_if_absent with atomic publishing.

    def stored_sha256(self, key: str) -> str:
        """sha256 of the bytes stored under ``key`` (read from the backend, not a cache)."""
        return self.sha256(key)

    def _verify_existing(self, key: str, sha: str, size: int) -> PutResult:
        actual = self.stored_sha256(key)
        if actual != sha:
            raise ObjectConflictError(key, sha, actual)
        return PutResult(key, sha, size, False)

    def put_if_absent(self, key: str, data: Source, *, expected_sha256: str | None = None) -> PutResult:
        """Write-once: store ``data`` unless ``key`` exists; if it exists, verify its sha256
        equals the source's (``created=False``) or raise :class:`ObjectConflictError`."""
        validate_key(key)
        with tempfile.TemporaryDirectory(prefix="dermpath-put-") as tmpdir:
            if not (_is_bytes(data) or _is_path(data)):
                spooled = Path(tmpdir) / "src"
                _write_temp(data, spooled)
                data = spooled
            sha, size = _hash_bytes(data) if _is_bytes(data) else _hash_file(data)
            _check_expected(key, sha, expected_sha256)
            if self.exists(key):
                return self._verify_existing(key, sha, size)
            if _is_bytes(data):
                self.put_bytes(key, bytes(data))
            else:
                self.put_file(key, Path(data))
        return PutResult(key, sha, size, True)

    def put_file_streaming(self, key: str, src: Source, *, if_absent: bool = False) -> PutResult:
        """Store a file (path or binary file object) in bounded memory and return its sha256.

        Overwrites like :meth:`put_file` unless ``if_absent`` (then :meth:`put_if_absent`)."""
        if if_absent:
            return self.put_if_absent(key, src)
        validate_key(key)
        with tempfile.TemporaryDirectory(prefix="dermpath-put-") as tmpdir:
            spooled = Path(tmpdir) / "src"
            sha, size = _write_temp(src, spooled)
            self.put_file(key, spooled, move=True)
        return PutResult(key, sha, size, True)

    def put_content_addressed(self, prefix: str, data: Source, suffix: str = "") -> tuple[str, str]:
        """Store ``data`` write-once under ``<prefix>/<sha256><suffix>``; return ``(key, sha256)``.

        Storing the same bytes again is a no-op; a stored object whose bytes no longer
        match its name raises :class:`ObjectConflictError` (corruption is never served)."""
        prefix = prefix.rstrip("/")
        validate_key(f"{prefix}/{'0' * 64}{suffix}")
        with tempfile.TemporaryDirectory(prefix="dermpath-cas-") as tmpdir:
            if _is_bytes(data):
                sha, _ = _hash_bytes(data)
            else:
                spooled = Path(tmpdir) / "src"
                sha, _ = _write_temp(data, spooled)
                data = spooled
            key = validate_key(f"{prefix}/{sha}{suffix}")
            self.put_if_absent(key, data, expected_sha256=sha)
        return key, sha


class LocalObjectStore(ObjectStore):
    backend = "local"

    def __init__(self, root: Path) -> None:
        self.root = Path(root).resolve()
        self.root.mkdir(parents=True, exist_ok=True)
        try:
            os.chmod(self.root, 0o700)
        except OSError:
            pass

    def _path(self, key: str) -> Path:
        validate_key(key)
        p = (self.root / key).resolve()
        if self.root not in p.parents:
            raise StoreError("object key escapes the store root")
        return p

    def _prepare(self, key: str) -> Path:
        p = self._path(key)
        p.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        return p

    def put_file(self, key: str, src: Path, *, move: bool = False) -> int:
        dest = self._prepare(key)
        tmp = _temp_name(dest)
        try:
            if move:
                shutil.move(str(src), tmp)
            else:
                shutil.copyfile(src, tmp)
            os.chmod(tmp, 0o600)
            os.replace(tmp, dest)
        finally:
            tmp.unlink(missing_ok=True)
        return dest.stat().st_size

    def put_bytes(self, key: str, data: bytes) -> int:
        dest = self._prepare(key)
        tmp = _temp_name(dest)
        try:
            fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
            with os.fdopen(fd, "wb") as fh:
                fh.write(data)
            os.replace(tmp, dest)
        finally:
            tmp.unlink(missing_ok=True)
        return len(data)

    def put_if_absent(self, key: str, data: Source, *, expected_sha256: str | None = None) -> PutResult:
        """Atomic write-once: the temp file is hard-linked to the key, which fails if the
        name exists, so exactly one of several concurrent writers creates the object and
        the others verify it. Never overwrites."""
        dest = self._prepare(key)
        if dest.is_file() and (_is_bytes(data) or _is_path(data)):
            sha, size = _hash_bytes(data) if _is_bytes(data) else _hash_file(data)
            _check_expected(key, sha, expected_sha256)
            return self._verify_existing(key, sha, size)
        tmp = _temp_name(dest)
        try:
            sha, size = _write_temp(data, tmp)
            _check_expected(key, sha, expected_sha256)
            return self._publish(tmp, dest, key, sha, size)
        finally:
            tmp.unlink(missing_ok=True)

    def _publish(self, tmp: Path, dest: Path, key: str, sha: str, size: int) -> PutResult:
        """Make the fully written ``tmp`` visible as ``dest`` without ever overwriting."""
        try:
            os.link(tmp, dest)
            return PutResult(key, sha, size, True)
        except FileExistsError:
            return self._verify_existing(key, sha, size)
        except OSError as exc:
            if exc.errno not in (errno.EPERM, errno.ENOTSUP, errno.EOPNOTSUPP, errno.EXDEV, errno.EMLINK):
                raise
        # Filesystem without hard links: check-then-rename, then re-verify (best effort; a
        # concurrent writer of different bytes is detected after the fact, not prevented).
        if dest.is_file():
            return self._verify_existing(key, sha, size)
        os.replace(tmp, dest)
        self._verify_existing(key, sha, size)
        return PutResult(key, sha, size, True)

    def put_file_streaming(self, key: str, src: Source, *, if_absent: bool = False) -> PutResult:
        if if_absent:
            return self.put_if_absent(key, src)
        dest = self._prepare(key)
        tmp = _temp_name(dest)
        try:
            sha, size = _write_temp(src, tmp)
            os.replace(tmp, dest)
        finally:
            tmp.unlink(missing_ok=True)
        return PutResult(key, sha, size, True)

    def put_content_addressed(self, prefix: str, data: Source, suffix: str = "") -> tuple[str, str]:
        prefix = prefix.rstrip("/")
        validate_key(f"{prefix}/{'0' * 64}{suffix}")
        staging = self.root / ".staging"  # inside the root: same filesystem, never a valid key
        staging.mkdir(mode=0o700, exist_ok=True)
        tmp = staging / f"{os.getpid()}.{uuid.uuid4().hex}.tmp"
        try:
            sha, size = _write_temp(data, tmp)
            key = validate_key(f"{prefix}/{sha}{suffix}")
            self._publish(tmp, self._prepare(key), key, sha, size)
        finally:
            tmp.unlink(missing_ok=True)
        return key, sha

    def stored_sha256(self, key: str) -> str:
        return self.sha256(key)

    def get_bytes(self, key: str) -> bytes:
        return self._path(key).read_bytes()

    def open_read(self, key: str) -> BinaryIO:
        return open(self._path(key), "rb")

    def exists(self, key: str) -> bool:
        return self._path(key).is_file()

    def size(self, key: str) -> int:
        return self._path(key).stat().st_size

    def delete(self, key: str) -> None:
        p = self._path(key)
        if p.exists():
            p.unlink()

    def local_path(self, key: str) -> Path:
        p = self._path(key)
        if not p.is_file():
            raise StoreError(f"object not found: {key}")
        return p

    def health(self) -> dict:
        try:
            probe = self.root / ".health"
            probe.write_text(str(time.time()))
            probe.unlink()
            return {"status": "ok", "backend": self.backend, "root_is_private": True}
        except OSError as exc:
            return {"status": "error", "backend": self.backend, "error": str(exc)}


class S3ObjectStore(ObjectStore):
    """S3-compatible store. UNVERIFIED (no S3/MinIO endpoint available when written)."""

    backend = "s3"

    def __init__(self, settings: Settings) -> None:
        self.settings = settings
        self.bucket = settings.s3_bucket
        self.cache_root = settings.cache_dir / "s3"
        self._client = None
        self._import_error: str | None = None
        try:
            import boto3  # noqa: F401  (lazy optional dependency)
        except ImportError as exc:
            self._import_error = f"boto3 is not installed ({exc})"

    def _c(self):
        if self._import_error:
            raise StoreDependencyError("boto3", self._import_error)
        if not self.bucket:
            raise StoreDependencyError("WB_S3_BUCKET", "WB_S3_BUCKET is not configured")
        if self._client is None:
            import boto3

            self._client = boto3.client(
                "s3",
                endpoint_url=self.settings.s3_endpoint,
                region_name=self.settings.s3_region,
                aws_access_key_id=self.settings.s3_access_key,
                aws_secret_access_key=self.settings.s3_secret_key,
            )
        return self._client

    def put_file(self, key: str, src: Path, *, move: bool = False) -> int:
        validate_key(key)
        self._c().upload_file(str(src), self.bucket, key)
        size = Path(src).stat().st_size
        if move:
            Path(src).unlink(missing_ok=True)
        return size

    def put_bytes(self, key: str, data: bytes) -> int:
        validate_key(key)
        self._c().put_object(Bucket=self.bucket, Key=key, Body=data)
        return len(data)

    def get_bytes(self, key: str) -> bytes:
        validate_key(key)
        return self._c().get_object(Bucket=self.bucket, Key=key)["Body"].read()

    def stored_sha256(self, key: str) -> str:
        """Hash the object streamed from S3 (never the local mirror, which may be stale)."""
        validate_key(key)
        body = self._c().get_object(Bucket=self.bucket, Key=key)["Body"]
        h = hashlib.sha256()
        try:
            for block in iter(lambda: body.read(_CHUNK), b""):
                h.update(block)
        finally:
            close = getattr(body, "close", None)
            if close:
                close()
        return h.hexdigest()

    @staticmethod
    def _error_code(exc: Exception) -> str:
        return str((getattr(exc, "response", None) or {}).get("Error", {}).get("Code", ""))

    def put_if_absent(self, key: str, data: Source, *, expected_sha256: str | None = None) -> PutResult:
        """Write-once via a conditional ``PUT`` (``If-None-Match: *``): S3 (since 2024) and
        recent MinIO refuse the write with 412 when the key exists, and then the stored
        object is verified by sha256. Clients too old to send the header fall back to
        head-then-put, which is NOT atomic (a warning is logged). Single ``PUT``, so objects
        are limited to 5 GB. UNVERIFIED against a live endpoint (none available here)."""
        validate_key(key)
        client = self._c()
        with tempfile.TemporaryDirectory(prefix="dermpath-put-") as tmpdir:
            if not (_is_bytes(data) or _is_path(data)):
                spooled = Path(tmpdir) / "src"
                _write_temp(data, spooled)
                data = spooled
            sha, size = _hash_bytes(data) if _is_bytes(data) else _hash_file(data)
            _check_expected(key, sha, expected_sha256)
            body = bytes(data) if _is_bytes(data) else open(data, "rb")
            try:
                try:
                    client.put_object(Bucket=self.bucket, Key=key, Body=body, IfNoneMatch="*",
                                      Metadata={"sha256": sha})
                    return PutResult(key, sha, size, True)
                except Exception as exc:
                    if self._error_code(exc) in ("PreconditionFailed", "412", "ConditionalRequestConflict", "409"):
                        return self._verify_existing(key, sha, size)
                    if not (type(exc).__name__ == "ParamValidationError" and "IfNoneMatch" in str(exc)):
                        raise
                log.warning("S3 client cannot send If-None-Match; put_if_absent(%s) falls back to a non-atomic "
                            "head-then-put", key)
                if self.exists(key):
                    return self._verify_existing(key, sha, size)
                if not isinstance(body, bytes):
                    body.seek(0)
                client.put_object(Bucket=self.bucket, Key=key, Body=body, Metadata={"sha256": sha})
                return PutResult(key, sha, size, True)
            finally:
                if not isinstance(body, bytes):
                    body.close()

    def open_read(self, key: str) -> BinaryIO:
        return open(self.local_path(key), "rb")

    def exists(self, key: str) -> bool:
        validate_key(key)
        try:
            self._c().head_object(Bucket=self.bucket, Key=key)
            return True
        except StoreDependencyError:
            raise
        except Exception:
            return False

    def size(self, key: str) -> int:
        validate_key(key)
        return int(self._c().head_object(Bucket=self.bucket, Key=key)["ContentLength"])

    def delete(self, key: str) -> None:
        validate_key(key)
        self._c().delete_object(Bucket=self.bucket, Key=key)

    def local_path(self, key: str) -> Path:
        validate_key(key)
        dest = (self.cache_root / key).resolve()
        if not dest.is_file():
            dest.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
            tmp = _temp_name(dest)
            try:
                self._c().download_file(self.bucket, key, str(tmp))
                os.chmod(tmp, 0o600)
                os.replace(tmp, dest)
            finally:
                tmp.unlink(missing_ok=True)
        return dest

    def health(self) -> dict:
        if self._import_error:
            return {"status": "missing_dependency", "backend": self.backend, "dependency": "boto3",
                    "message": self._import_error}
        if not self.bucket:
            return {"status": "misconfigured", "backend": self.backend, "dependency": "WB_S3_BUCKET"}
        try:
            self._c().head_bucket(Bucket=self.bucket)
            return {"status": "ok", "backend": self.backend, "bucket": self.bucket}
        except Exception as exc:  # pragma: no cover - needs a live endpoint
            return {"status": "error", "backend": self.backend, "error": type(exc).__name__}


_store: ObjectStore | None = None
_store_lock = threading.Lock()


def get_store() -> ObjectStore:
    global _store
    if _store is None:
        with _store_lock:
            if _store is None:
                settings = get_settings()
                if settings.object_store == "s3":
                    _store = S3ObjectStore(settings)
                else:
                    _store = LocalObjectStore(settings.objects_dir)
    return _store


def reset_store() -> None:
    global _store
    _store = None


