"""Private object storage and signed, short-lived slide access tokens.

``LocalObjectStore`` (default) keeps objects under ``var/objects`` (mode 0700 dirs, 0600
files), never under a web root. Objects are reachable only through API routes.

``S3ObjectStore`` targets S3-compatible storage (MinIO in docker-compose). boto3 is
imported lazily; if it is not installed the store reports ``missing_dependency`` in
``/health`` and every operation raises :class:`StoreDependencyError`. Nothing crashes at
import time. UNVERIFIED here: no MinIO/S3 endpoint is available in this environment.

Object keys are generated by the server (``projects/<pid>/slides/<sid>/original.svs``);
user-supplied filenames are never used as keys.
"""

from __future__ import annotations

import hashlib
import os
import re
import shutil
import threading
import time
from abc import ABC, abstractmethod
from pathlib import Path
from typing import BinaryIO

from .config import Settings, get_settings
from .signing import TokenError, sign, verify

_KEY_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.\-/]{0,299}$")
ACCESS_CONTEXT = "slide-access"


class StoreError(Exception):
    pass


class StoreDependencyError(StoreError):
    def __init__(self, dependency: str, message: str) -> None:
        super().__init__(message)
        self.dependency = dependency


def validate_key(key: str) -> str:
    if not _KEY_RE.match(key) or ".." in key.split("/") or "//" in key or key.endswith("/"):
        raise StoreError(f"invalid object key: {key!r}")
    return key


class ObjectStore(ABC):
    backend: str = "abstract"

    @abstractmethod
    def put_file(self, key: str, src: Path, *, move: bool = False) -> int: ...

    @abstractmethod
    def put_bytes(self, key: str, data: bytes) -> int: ...

    @abstractmethod
    def get_bytes(self, key: str) -> bytes: ...

    @abstractmethod
    def open_read(self, key: str) -> BinaryIO: ...

    @abstractmethod
    def exists(self, key: str) -> bool: ...

    @abstractmethod
    def size(self, key: str) -> int: ...

    @abstractmethod
    def delete(self, key: str) -> None: ...

    @abstractmethod
    def local_path(self, key: str) -> Path:
        """A filesystem path for libraries that need one (OpenSlide). S3 downloads to a
        private cache first."""

    @abstractmethod
    def health(self) -> dict: ...

    def sha256(self, key: str) -> str:
        h = hashlib.sha256()
        with self.open_read(key) as fh:
            for block in iter(lambda: fh.read(1024 * 1024), b""):
                h.update(block)
        return h.hexdigest()


class LocalObjectStore(ObjectStore):
    backend = "local"

    def __init__(self, root: Path) -> None:
        self.root = Path(root).resolve()
        self.root.mkdir(parents=True, exist_ok=True)
        try:
            os.chmod(self.root, 0o700)
        except OSError:
            pass

    def _path(self, key: str) -> Path:
        validate_key(key)
        p = (self.root / key).resolve()
        if self.root not in p.parents:
            raise StoreError("object key escapes the store root")
        return p

    def _prepare(self, key: str) -> Path:
        p = self._path(key)
        p.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        return p

    def put_file(self, key: str, src: Path, *, move: bool = False) -> int:
        dest = self._prepare(key)
        tmp = dest.with_name(dest.name + ".tmp")
        if move:
            shutil.move(str(src), tmp)
        else:
            shutil.copyfile(src, tmp)
        os.chmod(tmp, 0o600)
        os.replace(tmp, dest)
        return dest.stat().st_size

    def put_bytes(self, key: str, data: bytes) -> int:
        dest = self._prepare(key)
        tmp = dest.with_name(dest.name + ".tmp")
        fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "wb") as fh:
            fh.write(data)
        os.replace(tmp, dest)
        return len(data)

    def get_bytes(self, key: str) -> bytes:
        return self._path(key).read_bytes()

    def open_read(self, key: str) -> BinaryIO:
        return open(self._path(key), "rb")

    def exists(self, key: str) -> bool:
        return self._path(key).is_file()

    def size(self, key: str) -> int:
        return self._path(key).stat().st_size

    def delete(self, key: str) -> None:
        p = self._path(key)
        if p.exists():
            p.unlink()

    def local_path(self, key: str) -> Path:
        p = self._path(key)
        if not p.is_file():
            raise StoreError(f"object not found: {key}")
        return p

    def health(self) -> dict:
        try:
            probe = self.root / ".health"
            probe.write_text(str(time.time()))
            probe.unlink()
            return {"status": "ok", "backend": self.backend, "root_is_private": True}
        except OSError as exc:
            return {"status": "error", "backend": self.backend, "error": str(exc)}


class S3ObjectStore(ObjectStore):
    """S3-compatible store. UNVERIFIED (no S3/MinIO endpoint available when written)."""

    backend = "s3"

    def __init__(self, settings: Settings) -> None:
        self.settings = settings
        self.bucket = settings.s3_bucket
        self.cache_root = settings.cache_dir / "s3"
        self._client = None
        self._import_error: str | None = None
        try:
            import boto3  # noqa: F401  (lazy optional dependency)
        except ImportError as exc:
            self._import_error = f"boto3 is not installed ({exc})"

    def _c(self):
        if self._import_error:
            raise StoreDependencyError("boto3", self._import_error)
        if not self.bucket:
            raise StoreDependencyError("WB_S3_BUCKET", "WB_S3_BUCKET is not configured")
        if self._client is None:
            import boto3

            self._client = boto3.client(
                "s3",
                endpoint_url=self.settings.s3_endpoint,
                region_name=self.settings.s3_region,
                aws_access_key_id=self.settings.s3_access_key,
                aws_secret_access_key=self.settings.s3_secret_key,
            )
        return self._client

    def put_file(self, key: str, src: Path, *, move: bool = False) -> int:
        validate_key(key)
        self._c().upload_file(str(src), self.bucket, key)
        size = Path(src).stat().st_size
        if move:
            Path(src).unlink(missing_ok=True)
        return size

    def put_bytes(self, key: str, data: bytes) -> int:
        validate_key(key)
        self._c().put_object(Bucket=self.bucket, Key=key, Body=data)
        return len(data)

    def get_bytes(self, key: str) -> bytes:
        validate_key(key)
        return self._c().get_object(Bucket=self.bucket, Key=key)["Body"].read()

    def open_read(self, key: str) -> BinaryIO:
        return open(self.local_path(key), "rb")

    def exists(self, key: str) -> bool:
        validate_key(key)
        try:
            self._c().head_object(Bucket=self.bucket, Key=key)
            return True
        except StoreDependencyError:
            raise
        except Exception:
            return False

    def size(self, key: str) -> int:
        validate_key(key)
        return int(self._c().head_object(Bucket=self.bucket, Key=key)["ContentLength"])

    def delete(self, key: str) -> None:
        validate_key(key)
        self._c().delete_object(Bucket=self.bucket, Key=key)

    def local_path(self, key: str) -> Path:
        validate_key(key)
        dest = (self.cache_root / key).resolve()
        if not dest.is_file():
            dest.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
            tmp = dest.with_name(dest.name + ".tmp")
            self._c().download_file(self.bucket, key, str(tmp))
            os.chmod(tmp, 0o600)
            os.replace(tmp, dest)
        return dest

    def health(self) -> dict:
        if self._import_error:
            return {"status": "missing_dependency", "backend": self.backend, "dependency": "boto3",
                    "message": self._import_error}
        if not self.bucket:
            return {"status": "misconfigured", "backend": self.backend, "dependency": "WB_S3_BUCKET"}
        try:
            self._c().head_bucket(Bucket=self.bucket)
            return {"status": "ok", "backend": self.backend, "bucket": self.bucket}
        except Exception as exc:  # pragma: no cover - needs a live endpoint
            return {"status": "error", "backend": self.backend, "error": type(exc).__name__}


_store: ObjectStore | None = None
_store_lock = threading.Lock()


def get_store() -> ObjectStore:
    global _store
    if _store is None:
        with _store_lock:
            if _store is None:
                settings = get_settings()
                if settings.object_store == "s3":
                    _store = S3ObjectStore(settings)
                else:
                    _store = LocalObjectStore(settings.objects_dir)
    return _store


def reset_store() -> None:
    global _store
    _store = None


# --------------------------------------------------------------------------- access tokens


def issue_access_token(slide_id: str, user_id: str, ttl_seconds: int | None = None) -> tuple[str, int]:
    """HMAC over (slide id, user id, expiry). Default lifetime: 10 minutes."""
    ttl = ttl_seconds if ttl_seconds is not None else get_settings().access_token_ttl_seconds
    exp = int(time.time()) + int(ttl)
    return sign({"sid": slide_id, "uid": user_id, "exp": exp}, ACCESS_CONTEXT), exp


def verify_access_token(token: str, *, now: float | None = None) -> dict:
    payload = verify(token, ACCESS_CONTEXT, now=now)
    if not isinstance(payload.get("sid"), str) or not isinstance(payload.get("uid"), str):
        raise TokenError("token_malformed", "Access token lacks slide or user binding")
    return payload


def slide_key(project_id: str, slide_id: str, name: str) -> str:
    return validate_key(f"projects/{project_id}/slides/{slide_id}/{name}")
